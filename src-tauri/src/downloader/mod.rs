//! 下载能力。
//!
//! - [`verified`]：**唯一的下载链路**——多镜像、体积上限、空闲超时、
//!   SHA256 强制校验、已校验文件复用，并在服务端支持 Range 时**分片并行 + 断点续传**。
//!   适配器安装包与应用更新包都走它。
//! - [`verify`]：SHA256 计算与校验，被 `verified` 调用。
//!
//! # 关于分片并行与续传
//!
//! 这两个能力**都在 `verified` 里**，不另开实现：crates.io 上没有"多连接并行 + 续传"
//! 的成熟通用下载库（同类需求要么调用外部 `aria2c`/`axel`，要么自己用 `reqwest` + `tokio` 调度），
//! 所以这里把传输交给 `reqwest`、并发与超时交给 `tokio`，本模块只负责分片划分、
//! 续传记账与校验——保持"只有一个下载实现"这一点，比多一个库更重要。
//!
//! 服务端必须支持 HTTP Range（返回 206 + `Content-Range`）才会启用分片：
//! 资源服务器侧的实现见 `assets-server/src/server.rs::serve_abs`。
//! 不支持时自动退化为单流下载，功能不受影响，只是没有并行与续传。

