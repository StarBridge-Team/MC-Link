//! 下载能力。
//!
//! - [`verified`]：**唯一的下载链路**——流式、多镜像、体积上限、分片超时、
//!   SHA256 强制校验，并复用已校验的文件。适配器安装包与应用更新包都走它。
//! - [`verify`]：SHA256 计算与校验，被 `verified` 调用。
//!
//! # 为什么没有分片/续传下载器
//!
//! 这里曾经有一个多线程分片下载器（`downloader.rs` + `chunk.rs` + `policy.rs`，约 400 行），
//! 它的续传依赖服务端支持 HTTP Range。实测我们的资源服务器**不支持 Range**
//! （`HEAD` 不返回 `Accept-Ranges`，带 `Range` 的请求仍返回 `200` + chunked），
//! 因此它的分片与续传分支永远不会触发，只会退化成单线程下载——留着纯属两套实现并存。
//!
//! 若将来确实需要续传（例如更新包在弱网下反复失败），正确做法是**两步一起做**：
//!
//! 1. 让资源服务器支持 Range（`tiny_http` 侧返回 `206` 与 `Accept-Ranges`）；
//! 2. 把续传并入 [`verified`]，保持"只有一个下载实现"。
//!
//! 不要单独把旧的分片下载器捡回来：那正是之前"适配器校验了、更新包忘了校验"的成因。

