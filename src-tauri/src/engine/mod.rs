//! 内置联机引擎：进程外 P2P 内核的生命周期与运行时控制。
//!
//! # 为什么是独立层，而不是又一个插件
//!
//! `plugin/` 只认**能力方法**（`adapter.*` / `detector.*` …），它不该知道"某个内核的
//! 可执行文件放在哪、怎么起、怎么查它的对端"。把这段收进 `engine/` 之后：
//!
//! - 适配器（`plugin/builtin/*`）只描述"房间语义"，不碰进程与 CLI；
//! - 换引擎/加引擎（WGP 就位后）只需新增一个 `engine/<name>/`，适配器改一个构造参数；
//! - 进程与下载这些"会失败、会卡住"的东西集中在一处，便于统一加超时与清理。
//!
//! # 当前只有一件引擎
//!
//! [`easytier`]。WGP 尚未开发完成，因此**没有**留空壳模块——空壳会变成没人维护的
//! 半成品，等它真能跑起来再加。

